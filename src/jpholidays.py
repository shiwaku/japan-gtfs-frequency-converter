COVERED_FROM = min(_HOLIDAYS)
COVERED_TO = max(_HOLIDAYS)

_warned = False


def is_holiday(d: datetime.date) -> bool:
    """d が国民の祝日（振替休日・国民の休日を含む）か。"""
    global _warned
    if not (COVERED_FROM.year <= d.year <= COVERED_TO.year):
        if not _warned:
            print(
                f"WARN: 祝日テーブルの範囲外の日付を判定しました ({d})。"
                f"収録範囲は {COVERED_FROM.year}〜{COVERED_TO.year} 年です。"
                f"src/jpholidays.py に追記してください。",
                file=sys.stderr,
            )
            _warned = True
        return False
    return d in _HOLIDAYS


def name(d: datetime.date) -> str | None:
    return _HOLIDAYS.get(d)


def is_weekday(d: datetime.date) -> bool:
    """月〜金かつ祝日でない日。"""
    return d.weekday() < 5 and not is_holiday(d)
